import { describe, it, expect } from 'vitest'
import { bahtText } from '@/lib/baht-text'

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [4500, 'สี่พันห้าร้อยบาทถ้วน'],
    [12345, 'หนึ่งหมื่นสองพันสามร้อยสี่สิบห้าบาทถ้วน'],
    [1_000_000, 'หนึ่งล้านบาทถ้วน'],
    [21_000_001, 'ยี่สิบเอ็ดล้านหนึ่งบาทถ้วน'],
    [1250.5, 'หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์'],
    [4205.61, 'สี่พันสองร้อยห้าบาทหกสิบเอ็ดสตางค์'],
    [0.25, 'ยี่สิบห้าสตางค์'],
  ])('%s → %s', (n, w) => expect(bahtText(n)).toBe(w))
})
